import {
  Component,
  EventEmitter,
  Input,
  OnChanges,
  OnDestroy,
  OnInit,
  Output,
  SimpleChanges,
  ViewChild,
} from '@angular/core';
import { Router } from '@angular/router';
import { TranslateService } from '@ngx-translate/core';
import { SortEvent } from 'primeng/api';
import { Table } from 'primeng/table';
import { MetadataService } from 'src/app/services/metadata/metadata.service';
import { SelectOption } from '../../../core/models/select-option';
import { AppState, pagePermissions } from '../../../core/states/app-state';
import { ConfirmService } from '../../../services/confirmation.service';
import { AlertModalService } from '../../../services/modal-service/AlertModalService';
import { Popover } from 'primeng/popover';

@Component({
  selector: 'app-table-helper-lazy',
  templateUrl: './table-helper-lazy.component.html',
  styleUrls: ['./table-helper-lazy.component.scss'],
  standalone: false,
})
export class TableHelperLazyComponent implements OnInit, OnChanges, OnDestroy {
  @Input() objectName: any;
  @Input() data: any[] = [];
  @Input() acl: any; // Changed from any[] to any to allow object
  @Input() totalRecord: number = 0;
  @Input() fields: any[] = [];
  @Input() print: any;
  @Input() bankOu: any;
  @Input() loadingData: boolean = false;
  @Input() extrasButton: any[];
  @Input() extrasButton1: any[];
  @Input() extrasActionButton: any[];
  @Input() extrasActionButtonChild: any[];
  @Input() dataKeyParent: any = '';
  @Input() dataKeyChild: any = '';
  @Input() hideActionButton: boolean = false;
  @Input() expandable: boolean = false;
  @Input() showUpdate: boolean = true;
  @Input() showDelete: boolean = true;
  @Input() showFlag: boolean = false;
  @Input() enableFilter: boolean = true;
  @Input() enableRowHover: boolean = false;
  @Input() hoverPopoverContent: any = null;
  @Input() disableDelete: boolean = false;

  @Input() charges: any;
  @Output() refreshEvent = new EventEmitter<any>();
  @Output() statusEvent = new EventEmitter<any>();
  @Output() addEvent = new EventEmitter<any>();
  @Output() viewEvent = new EventEmitter<any>();
  @Output() updateEvent = new EventEmitter<any>();
  @Output() deleteEvent = new EventEmitter<any>();
  @Output() paggingEvent = new EventEmitter<any>();
  @Output() onLabelClickEvent = new EventEmitter<any>();
  @Output() printEvent = new EventEmitter<any>();
  @Output() changeFlagEvent = new EventEmitter<any>();
  @Output() rowHoverEvent = new EventEmitter<any>();
  @Output() retryEvent = new EventEmitter<any>();
  @Output() checkRowEvent = new EventEmitter<any>();

  @ViewChild('dtTrx') dtTrx: Table;
  @ViewChild('hoverPopover') hoverPopover: Popover;

  aclEnhanced: pagePermissions = null;
  initialData: any[] = [];
  isSorted: boolean = null;
  _selectedColumns: any[];
  globalFilter: any[] = [];
  metadata: any;
  first: number = 0;
  page: number = 1;
  rows: number = 10;
  rowtable: any[] = [
    { label: '10', value: 10 },
    { label: '25', value: 25 },
    { label: '50', value: 50 },
    {
      label: '100',
      value: 100,
    },
  ];
  rowsPerPage: number = 10;

  filterValue: any;
  modalVisibility = false;

  investigationStatusOptions: SelectOption[] = [
    { label: 'New', value: 'NEW' },
    { label: 'Investigating', value: 'INVESTIGATING' },
    { label: 'Resolved', value: 'RESOLVED' },
    { label: 'Closed', value: 'CLOSED' },
  ];
  accountStatusOptions: SelectOption[] = [
    { label: 'Active', value: 'ACTIVE' },
    { label: 'Blocked', value: 'BLOCKED' },
  ];

  customerStatusOptions: SelectOption[] = [
    { label: 'Allow', value: 'ALLOW' },
    { label: 'Flagged', value: 'FLAGGED' },
    { label: 'Blocked', value: 'BLOCKED' },
  ];

  hoveredRowData: any = null;
  currentHoverTarget: any = null;
  hoverTimeout: any = null;

  // Track if fields were auto-generated
  private isFieldsAutoGenerated: boolean = false;
  private lastDataStructureKeys: string = '';

  constructor(
    public router: Router,
    public appState: AppState,
    readonly alertModalService: AlertModalService,
    readonly metadataService: MetadataService,
    readonly confirmSvc: ConfirmService,
    readonly translate: TranslateService,
  ) {}

  ngOnInit() {
    this.metadata = this.metadataService.getMetadata();

    this.appState.currentPagePermissions$.subscribe((acl) => {
      // Prioritize manual ACL input if available, otherwise use state ACL
      this.aclEnhanced = this.acl || acl;
    });

    this.initializeFields();
  }

  ngOnChanges(changes: SimpleChanges): void {
    if (changes['acl']) {
      this.aclEnhanced = this.acl || this.aclEnhanced;
    }

    // Handle fields input changes first
    if (changes['fields']) {
      if (
        changes['fields'].currentValue &&
        changes['fields'].currentValue.length > 0
      ) {
        // Fields were manually provided
        this.isFieldsAutoGenerated = false;
        this.initializeFields();
      } else if (
        changes['fields'].currentValue &&
        changes['fields'].currentValue.length === 0
      ) {
        // Fields were explicitly set to empty, enable auto-generation
        this.isFieldsAutoGenerated = true;
      }
    }

    if (changes['data']) {
      this.initialData = this.data;

      const currentStructureKeys = this.getDataStructureKeys();
      const structureChanged =
        currentStructureKeys !== this.lastDataStructureKeys;

      if (this.data && this.data.length > 0) {
        const shouldRegenerate =
          this.fields.length === 0 ||
          (this.isFieldsAutoGenerated &&
            structureChanged &&
            this.lastDataStructureKeys !== '');

        if (shouldRegenerate) {
          // Clear existing fields before regenerating
          this.fields = [];
          this.initializeFields();
          this.lastDataStructureKeys = currentStructureKeys;
        } else if (
          this.lastDataStructureKeys === '' &&
          this.isFieldsAutoGenerated
        ) {
          // First time initialization
          this.initializeFields();
          this.lastDataStructureKeys = currentStructureKeys;
        }
      }
    }

    if (changes['hoverPopoverContent'] && this.hoverPopoverContent) {
      if (this.currentHoverTarget && this.hoveredRowData) {
        setTimeout(() => {
          if (this.hoverPopover && this.hoveredRowData) {
            this.hoverPopover.show(null, this.currentHoverTarget);
          }
        }, 50);
      }
    }
  }

  ngOnDestroy() {
    if (this.hoverTimeout) {
      clearTimeout(this.hoverTimeout);
    }
  }

  private getDataStructureKeys(): string {
    if (!this.data || this.data.length === 0) {
      return '';
    }
    return Object.keys(this.data[0]).sort().join(',');
  }

  private initializeFields() {
    // If fields are empty, generate them from data
    if (this.fields.length === 0 && this.data && this.data.length > 0) {
      this.fields = this.generateFieldsFromData();
      this.isFieldsAutoGenerated = true;
      this.lastDataStructureKeys = this.getDataStructureKeys();
    } else if (this.fields.length > 0 && !this.isFieldsAutoGenerated) {
    }

    if (this.fields.length === 0) {
      return;
    }

    this.globalFilter = this.fields.map((data) => {
      return data.key;
    });

    this.fields = this.fields.map((elData: any) => {
      return {
        ...elData,
        field: elData.key,
        header: this.translate.instant(elData.label || elData.key),
        type: elData.type || 'text', // Default type to 'text' if not specified
      };
    });

    this._selectedColumns = this.fields.filter(
      (elData: any) => elData.key != 'komiUniqueID' && elData.key != 'id',
    );
  }

  private generateFieldsFromData(): any[] {
    if (!this.data || this.data.length === 0) {
      return [];
    }

    const firstRow = this.data[0];
    const generatedFields = [];

    for (const key in firstRow) {
      if (firstRow.hasOwnProperty(key)) {
        generatedFields.push({
          key: key,
          label: key,
          type: this.detectFieldType(firstRow[key]),
          align: 'left',
          width: 'auto',
        });
      }
    }

    return generatedFields;
  }

  private detectFieldType(value: any): string {
    if (value === null || value === undefined) {
      return 'text';
    }

    if (typeof value === 'number') {
      return 'number';
    }

    if (typeof value === 'boolean') {
      return 'checkbox-readonly';
    }

    if (value instanceof Date || this.isDateString(value)) {
      return 'date';
    }

    return 'text';
  }

  private isDateString(value: any): boolean {
    if (typeof value !== 'string') {
      return false;
    }
    const date = new Date(value);
    return !isNaN(date.getTime());
  }

  get selectedColumns(): any[] {
    return this._selectedColumns;
  }

  set selectedColumns(val: any[]) {
    this._selectedColumns = this.fields.filter((col) => val.includes(col));
  }

  customSort(event: SortEvent) {
    if (this.isSorted == null || this.isSorted === undefined) {
      this.isSorted = true;
      this.sortTableData(event);
    } else if (this.isSorted == true) {
      this.isSorted = false;
      this.sortTableData(event);
    } else if (this.isSorted == false) {
      this.isSorted = null;
      this.data = [...this.initialData];
      this.dtTrx.reset();
    }
  }

  clear(table: Table) {
    table.clear();
    this.isSorted = null;
    this.data = [...this.initialData];
    this.dtTrx.reset();
    this.filterValue = '';
  }

  sortTableData(event) {
    event.data.sort((data1, data2) => {
      let value1 = data1[event.field];
      let value2 = data2[event.field];
      let result = null;
      if (value1 == null && value2 != null) result = -1;
      else if (value1 != null && value2 == null) result = 1;
      else if (value1 == null && value2 == null) result = 0;
      else if (typeof value1 === 'string' && typeof value2 === 'string')
        result = value1.localeCompare(value2);
      else result = value1 < value2 ? -1 : value1 > value2 ? 1 : 0;

      return event.order * result;
    });
  }

  viewData(data: any) {
    this.viewEvent.emit(data);
  }

  editData(data: any) {
    this.updateEvent.emit(data);
  }

  onLabelClick(data: any) {
    this.updateEvent.emit(data);
  }

  toggleFlag(data: any) {
    this.changeFlagEvent.emit(data);
  }

  getScoreGradient(score: number): string {
    if (score <= 30) {
      return '#28a745';
    } else if (score <= 70) {
      const yellowIntensity = (score - 30) / 40;
      return `linear-gradient(90deg, #28a745 ${(1 - yellowIntensity) * 100}%, #ffc107 100%)`;
    } else {
      const redIntensity = (score - 70) / 30;
      return `linear-gradient(90deg, #ffc107 ${(1 - redIntensity) * 100}%, #dc3545 100%)`;
    }
  }

  async deleteConfirm(data: any) {
    if (await this.confirmSvc.confirmDelete()) {
      this.deleteEvent.emit(data);
    }
  }

  addData() {
    this.addEvent.emit();
  }

  paggingData(data: any) {
    this.page = data.page + 1;
    data.page = this.page;
    this.rows = data.rows;
    this.first = data.first;
    this.paggingEvent.emit(data);
  }

  changeRowsPerPage(event: any) {
    let dataRow = { page: 0, first: 0, rows: event.value, pageCount: 5 };
    this.paggingData(dataRow);
  }

  highlightSearch(text: string, search: string): string {
    const safeText = this.escapeHtml(String(text ?? ''));

    if (!search) return safeText;

    const pattern = new RegExp(`(${search})`, 'gi');
    return safeText.replace(pattern, `<span class="highlight">$1</span>`);
  }

  escapeHtml(text: string): string {
    return text
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  toDisplayString(value: any): string {
    return typeof value === 'object' ? JSON.stringify(value) : String(value);
  }

  negativeStatus = ['BLOCKED'];
  statusRemark: string = '';
  selectedData: any = null;
  selectedStatus: string = '';

  async onChangeStatus(event: any, selectedData: any) {
    this.statusRemark = '';
    this.selectedStatus = event || '';
    this.selectedData = selectedData || null;

    if (this.negativeStatus.includes(event)) {
      this.modalVisibility = true;
      return;
    }
    if (
      await this.confirmSvc.confirmCustomMessage(`Change Status to ${event} ?`)
    ) {
      this.statusEvent.emit({ data: this.selectedData, status: event });
    }
  }

  onSubmitStatus() {
    this.statusEvent.emit({
      data: this.selectedData,
      status: this.selectedStatus,
      remark: this.statusRemark,
    });
    this.modalVisibility = false;
  }

  onRowMouseEnter(event: any, rowData: any) {
    if (!this.enableRowHover) return;

    this.hoverPopover.hide();

    if (this.hoverTimeout) {
      clearTimeout(this.hoverTimeout);
      this.hoverTimeout = null;
    }

    this.hoveredRowData = rowData;
    this.currentHoverTarget = event.currentTarget;

    this.rowHoverEvent.emit(rowData);

    setTimeout(() => {
      if (this.hoverPopover && this.hoveredRowData === rowData) {
        this.hoverPopover.show(event, this.currentHoverTarget);
      }
    }, 200);
  }

  onRowMouseLeave() {
    if (!this.enableRowHover) return;

    this.hoverTimeout = setTimeout(() => {
      if (this.hoverPopover) {
        this.hoverPopover.hide();
      }
      this.hoveredRowData = null;
      this.currentHoverTarget = null;
    }, 1500);
  }
}
